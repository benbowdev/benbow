func writeMySQLLine(w io.Writer, m core.MySQLStatus) {
	fmt.Fprintf(w, "  MySQL %s on %s:%d (user %s; password: %s password)\n", m.Version, m.Host, m.Port, m.User, mysqlCLI(m.Engine))
}

// mysqlCLI is the command group of a MySQL server.
func mysqlCLI(engine string) string {
	if engine == core.EngineMySQL57 {
		return "benbow mysql57"
	}
	return "benbow mysql"
}

func mysqlTitle(engine string) string {
	if engine == core.EngineMySQL57 {
		return "MySQL 5.7"
	}
	return "MySQL"
}

type mysqlStatusResult core.MySQLStatus

func (r mysqlStatusResult) Text(w io.Writer) {
	m := core.MySQLStatus(r)
	if !m.Enabled {
		fmt.Fprintf(w, "%s is off. Turn it on with: %s enable\n", mysqlTitle(m.Engine), mysqlCLI(m.Engine))
		if m.Initialized {
			fmt.Fprintf(w, "Its databases are kept in %s until benbow uninstall.\n", m.DataDir)
		}
		return
	}
	fmt.Fprintf(w, "MySQL %s is %s\n", m.Version, running(m.Running))
	fmt.Fprintf(w, "  host     %s\n  port     %d\n  socket   %s\n  user     %s\n  password %s password (stored in the login keychain)\n",
		m.Host, m.Port, m.Socket, m.User, mysqlCLI(m.Engine))
}

type mysqlResult core.MySQLResult

func (r mysqlResult) Text(w io.Writer) {
	mysqlStatusResult(r.MySQLStatus).Text(w)
	if r.Enabled && !r.Applied {
		fmt.Fprintf(w, "Benbow is not running: %s starts with `benbow start`.\n", mysqlTitle(r.Engine))
	}
}

type mysqlCredentialsResult core.MySQLCredentials

func (r mysqlCredentialsResult) Text(w io.Writer) {
	fmt.Fprintf(w, "host     %s\nport     %d\nsocket   %s\nuser     %s\npassword %s\n", r.Host, r.Port, r.Socket, r.User, r.Password)
}

func (a *app) mysqlCmd() *cobra.Command {
	return a.mysqlServerCmd(core.EngineMySQL, "mysql", "Show or change Benbow's MySQL server", `Benbow runs MySQL 8.4 LTS on 127.0.0.1, port 3307 by default (3306 is usually
MAMP's). Databases live in Benbow's home; the root password is generated by
Benbow and kept in the login keychain.

PHP sites reach it with DB_HOST "localhost" (Benbow's socket) or
"127.0.0.1:3307".`, 3307)
}

func (a *app) mysql57Cmd() *cobra.Command {
	return a.mysqlServerCmd(core.EngineMySQL57, "mysql57", "Show or change the optional MySQL 5.7 server, for old sites", `Benbow can also run MySQL 5.7 next to 8.4, to test an old site against the
server it ran on: off until enabled, 127.0.0.1, port 3308 by default, root
password in the login keychain. MySQL 5.7 has had no fixes since October
2023: use it only for old sites, locally.

A site's database goes on it with --engine mysql57 (benbow db create,
benbow import archive). Sites reach it with DB_HOST "127.0.0.1:3308".`, 3308)
}

func (a *app) mysqlServerCmd(engine, use, short, long string, defaultPort int) *cobra.Command {
	title := mysqlTitle(engine)
	cmd := &cobra.Command{
		Use:   use,
		Short: short,
		Long:  long,
		Args:  cobra.NoArgs,
		RunE: a.withCore(func(ctx context.Context, c *core.Core, _ []string) (Result, error) {
			res, err := c.MySQLOf(ctx, engine)
			return mysqlStatusResult(res), err
		}),
	}
	var port int
	enable := &cobra.Command{
		Use:   "enable",
		Short: "Install, initialize and start " + title,
		Args:  cobra.NoArgs,
		RunE: a.withCore(func(ctx context.Context, c *core.Core, _ []string) (Result, error) {
			res, err := c.EnableMySQLOf(ctx, engine, port)
			return mysqlResult(res), err
		}),
	}
	enable.Flags().IntVar(&port, "port", 0, fmt.Sprintf("TCP port on 127.0.0.1 (default: first free from %d)", defaultPort))
	cmd.AddCommand(enable, &cobra.Command{
		Use:   "disable",
		Short: "Stop " + title + " (databases are kept)",
		Args:  cobra.NoArgs,
		RunE: a.withCore(func(ctx context.Context, c *core.Core, _ []string) (Result, error) {
			res, err := c.DisableMySQLOf(ctx, engine)
			return mysqlResult(res), err
		}),
	}, &cobra.Command{
		Use:   "password",
		Short: "Print the connection details, root password included",
		Args:  cobra.NoArgs,
		RunE: a.withCore(func(ctx context.Context, c *core.Core, _ []string) (Result, error) {
			res, err := c.MySQLCredentialsOf(ctx, engine)
			return mysqlCredentialsResult(res), err
		}),
	})
	return cmd
}
