// APISocketName is the daemon's API socket in the run directory.
const APISocketName = "covo.sock"

// adminerPHP runs Adminer, whatever the sites use.
const adminerPHP = "8.4"

// adminerLoginTTL is how long a one-time Adminer login stays valid.
const adminerLoginTTL = 60 * time.Second

type adminerLogin struct {
	creds   AdminerCredentials
	expires time.Time
}

// AdminerCredentials is what a one-time login hands to Adminer.
type AdminerCredentials struct {
	Server   string `json:"server"`
	Username string `json:"username"`
	Password string `json:"password"`
	DB       string `json:"db"`
	// Driver is Adminer's: "server" (MySQL) or "pgsql".
	Driver string `json:"driver"`
}

// AdminerLogin is a URL that logs into Adminer once, within a minute.
type AdminerLogin struct {
	URL     string    `json:"url"`
	Expires time.Time `json:"expires"`
}

// adminerDir holds Covo's front file for Adminer.
func (c *Core) adminerDir() string { return filepath.Join(c.Layout.Etc, "adminer") }

// adminer installs the pinned Adminer while MySQL is enabled, writes the
// front file that handles one-time logins, and returns how Caddy serves
// it, or nil.
func (c *Core) adminer(ctx context.Context) (*caddy.Adminer, error) {
	on, err := c.databasesEnabled(ctx)
	if err != nil || !on {
		return nil, err
	}
	// The build with every driver: MySQL and PostgreSQL.
	art, err := c.pinned(ctx, "adminer-full", "")
	if err != nil {
		return nil, err
	}
	inst, err := c.Installer.Install(ctx, art)
	if err != nil {
		return nil, err
	}
	front, err := adminerFront(filepath.Join(inst.Dir, art.Files[0]), c.Layout.Socket(APISocketName))
	if err != nil {
		return nil, err
	}
	if _, err := fsutil.WriteAtomic(filepath.Join(c.adminerDir(), "index.php"), []byte(front), 0o644); err != nil {
		return nil, err
	}
	return &caddy.Adminer{Dir: c.adminerDir(), FPMSocket: c.Layout.Socket(socketName(adminerPHP))}, nil
}

// adminerFront is index.php in front of adminer.php. With ?covo_login=<token>
// it asks the Covo daemon, over its Unix socket, for the credentials behind
// the token (valid once, for a minute) and logs in with them, so passwords
// never travel in URLs, the clipboard or files.
func adminerFront(adminerPath, apiSocket string) (string, error) {
	for _, p := range []string{adminerPath, apiSocket} {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
		if strings.Contains(p, "'") {
			return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("path %q contains a quote", p))
		}
	}
	return `<?php
// Generated by Covo. Do not edit: changes are overwritten.
if (isset($_GET['covo_login']) && empty($_POST['auth']) && preg_match('/^[0-9a-f]{64}$/', (string) $_GET['covo_login'])) {
	$ch = curl_init('http://covo/v1/adminer/redeem');
	curl_setopt_array($ch, [
		CURLOPT_UNIX_SOCKET_PATH => '` + apiSocket + `',
		CURLOPT_POST => true,
		CURLOPT_POSTFIELDS => json_encode(['token' => $_GET['covo_login']]),
		CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
		CURLOPT_RETURNTRANSFER => true,
		CURLOPT_TIMEOUT => 5,
	]);
	$answer = json_decode((string) curl_exec($ch), true);
	if (!empty($answer['ok'])) {
		$d = $answer['data'];
		$_POST['auth'] = ['driver' => $d['driver'] ?: 'server', 'server' => $d['server'], 'username' => $d['username'],
			'password' => $d['password'], 'db' => $d['db'], 'permanent' => ''];
		define('COVO_LOGIN', true);
	}
}

function adminer_object() {
	class CovoAdminer extends Adminer\Adminer {
		// A Covo login has no form token: the daemon already vouched for it.
		function verifyLoginToken() {
			return !defined('COVO_LOGIN');
		}
	}
	return new CovoAdminer;
}

require '` + adminerPath + `';
`, nil
}

// NewAdminerLogin returns a one-time URL that opens Adminer logged in: as
// the site's database user on its database, or as root with site "".
func (c *Core) NewAdminerLogin(ctx context.Context, site, engine string) (AdminerLogin, error) {
	st, err := c.Status(ctx)
	if err != nil {
		return AdminerLogin{}, err
	}
	if st.AdminerURL == "" {
		return AdminerLogin{}, errcode.Errorf(errcode.Unsupported, "Adminer needs MySQL or PostgreSQL: turn one on first (covo mysql enable)")
	}
	if !st.Running {
		return AdminerLogin{}, errcode.Errorf(errcode.Conflict, "Covo is stopped: start it first (covo start)")
	}
	var creds AdminerCredentials
	switch {
	case site != "":
		db, err := c.GetSiteDatabase(ctx, site)
		if err != nil {
			return AdminerLogin{}, err
		}
		creds = AdminerCredentials{Server: "localhost", Username: db.User, Password: db.Password, DB: db.Database, Driver: "server"}
		if db.Engine == EnginePostgres {
			creds.Server, creds.Driver = "127.0.0.1:"+strconv.Itoa(db.Port), "pgsql"
		}
	case engine == EnginePostgres || (engine == "" && !st.MySQL.Enabled):
		root, err := c.PostgresCredentials(ctx)
		if err != nil {
			return AdminerLogin{}, err
		}
		creds = AdminerCredentials{Server: "127.0.0.1:" + strconv.Itoa(root.Port), Username: root.User, Password: root.Password, DB: "postgres", Driver: "pgsql"}
	default:
		root, err := c.MySQLCredentials(ctx)
		if err != nil {
			return AdminerLogin{}, err
		}
		creds = AdminerCredentials{Server: "localhost", Username: mysql.User, Password: root.Password, Driver: "server"}
	}
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return AdminerLogin{}, fmt.Errorf("random token: %w", err)
	}
	token := hex.EncodeToString(b)
	expires := time.Now().Add(adminerLoginTTL)

	c.adminerMu.Lock()
	if c.adminerLogins == nil {
		c.adminerLogins = map[string]adminerLogin{}
	}
	for t, l := range c.adminerLogins {
		if time.Now().After(l.expires) {
			delete(c.adminerLogins, t)
		}
	}
	c.adminerLogins[token] = adminerLogin{creds: creds, expires: expires}
	c.adminerMu.Unlock()

	q := url.Values{"covo_login": {token}}
	if creds.DB != "" {
		q.Set("db", creds.DB)
	}
	return AdminerLogin{URL: st.AdminerURL + "?" + q.Encode(), Expires: expires}, nil
}

// RedeemAdminerLogin hands out the credentials of a one-time login and
// forgets it.
func (c *Core) RedeemAdminerLogin(token string) (AdminerCredentials, error) {
	c.adminerMu.Lock()
	defer c.adminerMu.Unlock()
	l, ok := c.adminerLogins[token]
	delete(c.adminerLogins, token)
	if !ok || time.Now().After(l.expires) {
		return AdminerCredentials{}, errcode.Errorf(errcode.NotFound, "unknown or expired Adminer login")
	}
	return l.creds, nil
}
