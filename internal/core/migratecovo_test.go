func TestParseCovoResolver(t *testing.T) {
	file := "# Generated by Covo. Removed by `covo domains disable` and `covo uninstall`.\n" +
		"# covo-home: /Users/me/Library/Application Support/covo\n# covo-created-dir: yes\nnameserver 127.0.0.1\nport 53535\n"
	home, created, port, ok := parseCovoResolver(file)
	if !ok || home != "/Users/me/Library/Application Support/covo" || !created || port != 53535 {
		t.Errorf("parse = %q %v %d %v", home, created, port, ok)
	}
	for _, other := range []string{"nameserver 10.0.0.1\n", "# Generated by Benbow.\n# benbow-home: /x\nport 1\n", ""} {
		if _, _, _, ok := parseCovoResolver(other); ok {
			t.Errorf("%q read as Covo's", other)
		}
	}
}

func TestCopyCovoKeychain(t *testing.T) {
	c := runCore(t)
	fake := keychain.NewFake()
	c.keychainRun = fake.Run
	fake.Items["root@dev.old.mysql"] = "rootpw"
	fake.Items["shop@dev.old.mysql"] = "shoppw"
	fake.Items["covo_ro_abc@dev.old.mysql"] = "ro"
	fake.Items["shop@dev.old.appenv"] = `{"A":"1"}`
	fake.Items["root@dev.other.mysql"] = "not ours"
	copied, err := c.copyCovoKeychain(context.Background(), "dev.old")
	if err != nil {
		t.Fatal(err)
	}
	if len(copied) != 3 {
		t.Errorf("copied %d items: %+v", len(copied), copied)
	}
	for key, want := range map[string]string{
		"root@dev.benbow.mysql": "rootpw", "shop@dev.benbow.mysql": "shoppw", "shop@dev.benbow.appenv": `{"A":"1"}`,
	} {
		if got := fake.Items[key]; got != want {
			t.Errorf("%s = %q, want %q", key, got, want)
		}
	}
	if _, ok := fake.Items["covo_ro_abc@dev.benbow.mysql"]; ok {
		t.Error("a read-only user's password was copied")
	}
	if fake.Items["root@dev.old.mysql"] != "rootpw" {
		t.Error("the old item was changed before the migration finished")
	}
}

func TestMarkCovoComponents(t *testing.T) {
	bin := t.TempDir()
	caddy := filepath.Join(bin, "caddy", "2.11.7")
	cli := filepath.Join(bin, "php-cli", "8.4.23", "8.4.23")
	for _, d := range []string{caddy, cli} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(d, covoComponentMarker), []byte("abc\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := markCovoComponents(bin); err != nil {
		t.Fatal(err)
	}
	for _, d := range []string{caddy, cli} {
		if b, err := os.ReadFile(filepath.Join(d, components.MarkerFile)); err != nil || string(b) != "abc\n" {
			t.Errorf("%s: marker %q %v", d, b, err)
		}
		if _, err := os.Stat(filepath.Join(d, covoComponentMarker)); err != nil {
			t.Errorf("Covo's marker went away: %v", err)
		}
	}
	if err := markCovoComponents(filepath.Join(bin, "missing")); err != nil {
		t.Errorf("no bin folder: %v", err)
	}
}

func TestRemoveCovoBinary(t *testing.T) {
	c := runCore(t)
	bin := filepath.Join(c.Layout.Bin, "covo", "covo")
	if err := os.MkdirAll(filepath.Dir(bin), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(bin, []byte("x"), 0o755); err != nil {
		t.Fatal(err)
	}
	c.removeCovoBinary()
	if !fileExists(bin) {
		t.Fatal("removed without a migration")
	}
	if err := c.writeCovoState(covoMigrationState{From: "/x"}); err != nil {
		t.Fatal(err)
	}
	c.removeCovoBinary()
	if !fileExists(bin) {
		t.Fatal("removed before the migration finished")
	}
	if err := c.writeCovoState(covoMigrationState{From: "/x", Finished: true}); err != nil {
		t.Fatal(err)
	}
	c.removeCovoBinary()
	if fileExists(filepath.Dir(bin)) {
		t.Fatal("bin/covo kept after a finished migration")
	}
}
