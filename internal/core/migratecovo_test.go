func TestParseCovoResolver(t *testing.T) {
	file := "# Generated by Covo. Removed by `covo domains disable` and `covo uninstall`.\n" +
		"# covo-home: /Users/me/Library/Application Support/covo\n# covo-created-dir: yes\nnameserver 127.0.0.1\nport 53535\n"
	home, created, port, ok := parseCovoResolver(file)
	if !ok || home != "/Users/me/Library/Application Support/covo" || !created || port != 53535 {
		t.Errorf("parse = %q %v %d %v", home, created, port, ok)
	}
	for _, other := range []string{"nameserver 10.0.0.1\n", "# Generated by Benbow.\n# benbow-home: /x\nport 1\n", ""} {
		if _, _, _, ok := parseCovoResolver(other); ok {
			t.Errorf("%q read as Covo's", other)
		}
	}
}

func TestCopyCovoKeychain(t *testing.T) {
	c := runCore(t)
	fake := keychain.NewFake()
	c.keychainRun = fake.Run
	fake.Items["root@dev.old.mysql"] = "rootpw"
	fake.Items["shop@dev.old.mysql"] = "shoppw"
	fake.Items["covo_ro_abc@dev.old.mysql"] = "ro"
	fake.Items["shop@dev.old.appenv"] = `{"A":"1"}`
	fake.Items["root@dev.other.mysql"] = "not ours"
	copied, err := c.copyCovoKeychain(context.Background(), "dev.old")
	if err != nil {
		t.Fatal(err)
	}
	if len(copied) != 3 {
		t.Errorf("copied %d items: %+v", len(copied), copied)
	}
	for key, want := range map[string]string{
		"root@dev.benbow.mysql": "rootpw", "shop@dev.benbow.mysql": "shoppw", "shop@dev.benbow.appenv": `{"A":"1"}`,
	} {
		if got := fake.Items[key]; got != want {
			t.Errorf("%s = %q, want %q", key, got, want)
		}
	}
	if _, ok := fake.Items["covo_ro_abc@dev.benbow.mysql"]; ok {
		t.Error("a read-only user's password was copied")
	}
	if fake.Items["root@dev.old.mysql"] != "rootpw" {
		t.Error("the old item was changed before the migration finished")
	}
}
