// Package launchd generates launchd user agent plists and loads them into the
// user's GUI domain with launchctl. Plists stay inside the Covo home: they are
// bootstrapped from there, never copied to ~/Library/LaunchAgents.
//
// Every operation is scoped to labels under a prefix (dev.getcovo by
// default), so Covo never touches a service it did not create.
package launchd

import (
	"bufio"
	"bytes"
	"context"
	"encoding/xml"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"text/template"
	"time"

	"github.com/getcovo/covo/internal/errcode"
	"github.com/getcovo/covo/internal/fsutil"
)

// EnvLabelPrefix overrides the label prefix (used by tests to stay isolated).
const EnvLabelPrefix = "COVO_LABEL_PREFIX"

// DefaultPrefix is the label prefix of every Covo agent.
const DefaultPrefix = "dev.getcovo"

// Prefix returns the label prefix in effect.
func Prefix() string {
	if p := os.Getenv(EnvLabelPrefix); p != "" {
		return p
	}
	return DefaultPrefix
}

// Agent describes one launchd user agent.
type Agent struct {
	Label     string
	Program   string
	Args      []string
	Env       map[string]string
	WorkDir   string
	StdoutLog string
	StderrLog string
	// ExitTimeout is how many seconds launchd waits after SIGTERM before
	// SIGKILL (launchd's default, 20, if zero).
	ExitTimeout int
}

type envVar struct{ Key, Value string }

var plistTmpl = template.Must(template.New("plist").Funcs(template.FuncMap{"x": xmlEscape}).Parse(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by Covo. Do not edit: changes are overwritten. -->
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>{{x .Label}}</string>
	<key>ProgramArguments</key>
	<array>
		<string>{{x .Program}}</string>
{{- range .Args}}
		<string>{{x .}}</string>
{{- end}}
	</array>
{{- if .Env}}
	<key>EnvironmentVariables</key>
	<dict>
{{- range .Env}}
		<key>{{x .Key}}</key>
		<string>{{x .Value}}</string>
{{- end}}
	</dict>
{{- end}}
{{- if .WorkDir}}
	<key>WorkingDirectory</key>
	<string>{{x .WorkDir}}</string>
{{- end}}
	<key>StandardOutPath</key>
	<string>{{x .StdoutLog}}</string>
	<key>StandardErrorPath</key>
	<string>{{x .StderrLog}}</string>
	<key>RunAtLoad</key>
	<true/>
	<key>KeepAlive</key>
	<true/>
	<key>ThrottleInterval</key>
	<integer>5</integer>
{{- if .ExitTimeout}}
	<key>ExitTimeOut</key>
	<integer>{{.ExitTimeout}}</integer>
{{- end}}
	<key>ProcessType</key>
	<string>Interactive</string>
</dict>
</plist>
`))

func xmlEscape(s string) string {
	var b strings.Builder
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// Plist renders the agent's property list.
func Plist(a Agent) ([]byte, error) {
	env := make([]envVar, 0, len(a.Env))
	for k, v := range a.Env {
		env = append(env, envVar{k, v})
	}
	sort.Slice(env, func(i, j int) bool { return env[i].Key < env[j].Key })
	var buf bytes.Buffer
	err := plistTmpl.Execute(&buf, struct {
		Agent
		Env []envVar
	}{a, env})
	if err != nil {
		return nil, fmt.Errorf("render plist %s: %w", a.Label, err)
	}
	return buf.Bytes(), nil
}

// Status is the state of a loaded agent.
type Status struct {
	Label   string `json:"label"`
	PID     int    `json:"pid,omitempty"`
	Running bool   `json:"running"`
	// LastExit is the last exit status reported by launchd (0 if none).
	LastExit int `json:"last_exit,omitempty"`
}

// Launchctl drives launchctl for the current user's GUI domain.
type Launchctl struct {
	// Prefix scopes every operation; only labels starting with Prefix+"."
	// are ever listed, booted out or bootstrapped.
	Prefix string
	// Run executes launchctl; overridable in tests.
	Run func(ctx context.Context, args ...string) (string, error)
}

// New returns a Launchctl for the configured prefix.
func New() *Launchctl {
	return &Launchctl{Prefix: Prefix(), Run: runLaunchctl}
}

func runLaunchctl(ctx context.Context, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	var out bytes.Buffer
	cmd := exec.CommandContext(ctx, "/bin/launchctl", args...)
	cmd.Stdout, cmd.Stderr = &out, &out
	err := cmd.Run()
	if err != nil {
		return out.String(), fmt.Errorf("launchctl %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(out.String()))
	}
	return out.String(), nil
}

func domain() string { return "gui/" + strconv.Itoa(os.Getuid()) }

// Owns reports whether label belongs to this prefix.
func (l *Launchctl) Owns(label string) bool {
	return strings.HasPrefix(label, l.Prefix+".")
}

// List returns the loaded agents under the prefix.
func (l *Launchctl) List(ctx context.Context) (map[string]Status, error) {
	out, err := l.Run(ctx, "list")
	if err != nil {
		return nil, errcode.New(errcode.Service, err)
	}
	return l.parseList(out), nil
}

// parseList parses `launchctl list` ("PID\tStatus\tLabel" rows).
func (l *Launchctl) parseList(out string) map[string]Status {
	res := map[string]Status{}
	sc := bufio.NewScanner(strings.NewReader(out))
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if len(f) != 3 || !l.Owns(f[2]) {
			continue
		}
		s := Status{Label: f[2]}
		if pid, err := strconv.Atoi(f[0]); err == nil {
			s.PID, s.Running = pid, true
		}
		s.LastExit, _ = strconv.Atoi(f[1])
		res[s.Label] = s
	}
	return res
}

// Bootstrap loads the plist at path. The label must belong to the prefix.
func (l *Launchctl) Bootstrap(ctx context.Context, label, path string) error {
	if !l.Owns(label) {
		return errcode.Errorf(errcode.Internal, "refusing to bootstrap foreign label "+label)
	}
	if _, err := l.Run(ctx, "bootstrap", domain(), path); err != nil {
		return errcode.New(errcode.Service, err)
	}
	return nil
}

// Bootout unloads label (stopping its process) and waits until launchd has
// forgotten it. Booting out an agent that is not loaded is not an error.
func (l *Launchctl) Bootout(ctx context.Context, label string) error {
	if !l.Owns(label) {
		return errcode.Errorf(errcode.Internal, "refusing to boot out foreign label "+label)
	}
	loaded, err := l.List(ctx)
	if err != nil {
		return err
	}
	if _, ok := loaded[label]; !ok {
		return nil
	}
	if _, err := l.Run(ctx, "bootout", domain()+"/"+label); err != nil {
		// It may have gone away between List and bootout.
		if loaded, lerr := l.List(ctx); lerr == nil {
			if _, ok := loaded[label]; !ok {
				return nil
			}
		}
		return errcode.New(errcode.Service, err)
	}
	return l.waitGone(ctx, label)
}

func (l *Launchctl) waitGone(ctx context.Context, label string) error {
	deadline := time.Now().Add(10 * time.Second)
	for time.Now().Before(deadline) {
		loaded, err := l.List(ctx)
		if err != nil {
			return err
		}
		if _, ok := loaded[label]; !ok {
			return nil
		}
		time.Sleep(100 * time.Millisecond)
	}
	return errcode.Errorf(errcode.Service, "launchd did not unload "+label)
}

// Change describes what Apply did to one agent.
type Change struct {
	Label  string `json:"label"`
	Action string `json:"action"` // "started", "restarted", "unchanged", "stopped"
}

// Apply makes the loaded agents under the prefix match want: plists are
// written to dir, new agents are bootstrapped, agents whose plist changed are
// reloaded, and loaded agents not in want are booted out. It is idempotent.
func (l *Launchctl) Apply(ctx context.Context, dir string, want []Agent) ([]Change, error) {
	loaded, err := l.List(ctx)
	if err != nil {
		return nil, err
	}
	var changes []Change
	wanted := map[string]bool{}
	for _, a := range want {
		wanted[a.Label] = true
		action, err := l.applyOne(ctx, dir, a, loaded)
		if err != nil {
			return changes, err
		}
		changes = append(changes, Change{a.Label, action})
	}
	orphans := make([]string, 0)
	for label := range loaded {
		if !wanted[label] {
			orphans = append(orphans, label)
		}
	}
	sort.Strings(orphans)
	for _, label := range orphans {
		if err := l.Bootout(ctx, label); err != nil {
			return changes, err
		}
		_ = os.Remove(filepath.Join(dir, label+".plist"))
		changes = append(changes, Change{label, "stopped"})
	}
	return changes, nil
}

func (l *Launchctl) applyOne(ctx context.Context, dir string, a Agent, loaded map[string]Status) (string, error) {
	if !l.Owns(a.Label) {
		return "", errcode.Errorf(errcode.Internal, "agent label "+a.Label+" is outside prefix "+l.Prefix)
	}
	body, err := Plist(a)
	if err != nil {
		return "", err
	}
	path := filepath.Join(dir, a.Label+".plist")
	old, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("read %s: %w", path, err)
	}
	st, isLoaded := loaded[a.Label]
	changed := !bytes.Equal(old, body)
	if isLoaded && !changed && st.Running {
		return "unchanged", nil
	}
	if changed {
		if _, err := fsutil.WriteAtomic(path, body, 0o644); err != nil {
			return "", err
		}
	}
	action := "started"
	if isLoaded {
		if err := l.Bootout(ctx, a.Label); err != nil {
			return "", err
		}
		action = "restarted"
	}
	if err := l.Bootstrap(ctx, a.Label, path); err != nil {
		return "", err
	}
	return action, nil
}

// StopAll boots out every loaded agent under the prefix.
func (l *Launchctl) StopAll(ctx context.Context) ([]Change, error) {
	loaded, err := l.List(ctx)
	if err != nil {
		return nil, err
	}
	labels := make([]string, 0, len(loaded))
	for label := range loaded {
		labels = append(labels, label)
	}
	sort.Strings(labels)
	changes := []Change{}
	for _, label := range labels {
		if err := l.Bootout(ctx, label); err != nil {
			return changes, err
		}
		changes = append(changes, Change{label, "stopped"})
	}
	return changes, nil
}
