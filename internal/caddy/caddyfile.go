// Config is everything the Caddyfile depends on.
type Config struct {
	AdminSocket string
	HTTPSPort   int
	// HTTPPort, if set, redirects http:// on that port to HTTPS on
	// PublicHTTPS (the port in addresses, which may be forwarded to
	// HTTPSPort).
	HTTPPort    int
	PublicHTTPS int
	// Phone, if set, serves one site on the private network addresses.
	Phone      *Phone
	StorageDir string
	LogFile    string
	CA         CA
	Sites      []Site
	// Adminer, when set, is served at https://adminer.localhost.
	Adminer *Adminer
	// MailUIPort, when set, proxies https://mail.localhost to Mailpit.
	MailUIPort int
}

// Adminer is the database manager: one PHP file served by PHP-FPM.
type Adminer struct {
	Dir       string // holds index.php, which loads Adminer
	FPMSocket string
}

// Reserved domains.
const (
	AdminerDomain = "adminer.localhost"
	MailDomain    = "mail.localhost"
)

// CA is the certificate authority Caddy signs site certificates with. Benbow
// creates it (package ca): Caddy gets the root certificate without its key,
// and the intermediate with its key.
type CA struct {
	Name             string
	RootCert         string
	IntermediateCert string
	IntermediateKey  string
}

// Site is one virtual host.
type Site struct {
	Name      string
	Domain    string
	Aliases   []string
	Root      string
	FPMSocket string
	// AccessLog is the site's own request log; empty means none.
	AccessLog string
	// PHPValue is sent to PHP-FPM as PHP_VALUE: name=value lines (the
	// site's php.ini settings and error log).
	PHPValue string
	// ProbeDir, when set, gives requests carrying an X-Benbow-Probe header
	// (32 hex characters, sent by Benbow's fetch_page) their own PHP error log
	// <ProbeDir>/<id>.log; ProbePHPValue is PHPValue without the error log.
	ProbeDir      string
	ProbePHPValue string
	// Upstream, when set, makes the site a reverse proxy to a dev server on
	// localhost:Upstream (both 127.0.0.1 and ::1 are tried) instead of
	// PHP: Root, FPMSocket, PHPValue and the probe are then unused.
	Upstream int
	// UpstreamLocalHost sends Host: localhost:<Upstream> instead of the
	// site's domain, for dev servers that only accept localhost.
	UpstreamLocalHost bool
}

// ProbeHeader is the request header that sends one request's PHP errors to
// its own log.
const ProbeHeader = "X-Benbow-Probe"

