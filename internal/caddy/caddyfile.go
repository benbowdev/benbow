// Phone is a site opened on a phone: served under Host on the Mac's private
// addresses (Binds) only, plus a plain-HTTP page that installs the CA.
type Phone struct {
	Site      string
	Host      string
	Port      int
	Binds     []string
	Root      string
	FPMSocket string
	// PHPValue includes Benbow's auto_prepend_file for these requests.
	PHPValue string
	// LocalURL is replaced by PhoneURL in redirects (and, by the prepend
	// file, in pages).
	LocalURL, PhoneURL string
	// Laravel gets APP_URL from the environment.
	Laravel bool
	// Upstream is an app's port: requests go to its dev server instead of
	// PHP (UpstreamLocalHost: with Host localhost:<port>).
	Upstream          int
	UpstreamLocalHost bool
	CAPort            int
	CADir             string
	// PlainPort serves the same site over plain HTTP (no certificate to
	// install on the phone) at PlainURL; 0 for none.
	PlainPort int
	PlainURL  string
}

// PhoneVariant is one address the phone's site answers on.
type PhoneVariant struct {
	Address string // Caddy site address
	URL     string // what the site's pages and redirects use
	TLS     bool
}

// Variants are the HTTPS address and, if set, the plain HTTP one.
func (p Phone) Variants() []PhoneVariant {
	v := []PhoneVariant{{Address: "https://" + p.Host + ":" + strconv.Itoa(p.Port), URL: p.PhoneURL, TLS: true}}
	if p.PlainPort != 0 {
		v = append(v, PhoneVariant{Address: "http://:" + strconv.Itoa(p.PlainPort), URL: p.PlainURL})
	}
	return v
}

// Caddyfile renders cfg. Every path is validated with paths.CheckSafe so that
// it can be quoted verbatim (spaces are allowed).
func Caddyfile(cfg Config) (string, error) {
	check := []string{cfg.AdminSocket, cfg.StorageDir, cfg.LogFile, cfg.CA.RootCert, cfg.CA.IntermediateCert, cfg.CA.IntermediateKey}
	if cfg.Adminer != nil {
		check = append(check, cfg.Adminer.Dir, cfg.Adminer.FPMSocket)
	}
	if p := cfg.Phone; p != nil {
		check = append(check, p.CADir)
		if p.Upstream == 0 {
			check = append(check, p.Root, p.FPMSocket)
		} else if p.Upstream < 1 || p.Upstream > 65535 {
			return "", errcode.Newf(errcode.InvalidInput, "bad upstream port %d", p.Upstream)
		}
		if !hostRe.MatchString(p.Host) {
			return "", errcode.Newf(errcode.InvalidInput, "bad phone host %q", p.Host)
		}
		for _, b := range p.Binds {
			if ip := net.ParseIP(b); ip == nil || !ip.IsPrivate() {
				return "", errcode.Newf(errcode.InvalidInput, "phone address %q is not a private IP", b)
			}
		}
		for _, line := range strings.Split(p.PHPValue, "\n") {
			if p.Upstream == 0 && !phpValueRe.MatchString(line) {
				return "", errcode.Newf(errcode.InvalidInput, "bad PHP value %q", line)
			}
		}
		for _, u := range []string{p.LocalURL, p.PhoneURL, p.PlainURL} {
			if u == "" {
				continue
			}
			if strings.ContainsAny(u, "\"\\{} \n") {
				return "", errcode.Newf(errcode.InvalidInput, "bad URL %q", u)
			}
		}
	}
	for _, s := range cfg.Sites {
		if s.Upstream != 0 {
			if s.Upstream < 1 || s.Upstream > 65535 {
				return "", errcode.Newf(errcode.InvalidInput, "bad upstream port %d", s.Upstream)
			}
		} else {
			check = append(check, s.Root, s.FPMSocket)
		}
		if s.AccessLog != "" {
			check = append(check, s.AccessLog)
		}
		for _, v := range []string{s.PHPValue, s.ProbePHPValue} {
			for _, line := range strings.Split(v, "\n") {
				if v != "" && !phpValueRe.MatchString(line) {
					return "", errcode.Newf(errcode.InvalidInput, "bad PHP value %q", line)
				}
			}
		}
		if s.ProbeDir != "" {
			check = append(check, s.ProbeDir)
		}
		for _, d := range append([]string{s.Domain}, s.Aliases...) {
			if !hostRe.MatchString(d) {
				return "", errcode.Newf(errcode.InvalidInput, "bad domain %q", d)
			}
		}
	}
	for _, p := range check {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
	}
	if cfg.CA.Name == "" || strings.ContainsAny(cfg.CA.Name, "\"\\{}\n") {
		return "", errcode.Newf(errcode.InvalidInput, "bad CA name %q", cfg.CA.Name)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return "", fmt.Errorf("render Caddyfile: %w", err)
	}
	return buf.String(), nil
}

// hostRe is what a domain may contain in the Caddyfile (the core checks
// the actual rules).
var hostRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)

// phpValueRe is one PHP_VALUE line that can sit verbatim in a quoted
// Caddyfile token.
var phpValueRe = regexp.MustCompile(`^[a-z_.]+=[^"\\{}$\x00-\x1f]+$`)

// quote wraps s in double quotes. CheckSafe guarantees s holds no quote,
// backslash or brace that would need escaping.
func quote(s string) string { return `"` + s + `"` }

// RedirectPort is ":port" for http → https redirects, or "" for 443.
func (cfg Config) RedirectPort() string {
	p := cfg.PublicHTTPS
	if p == 0 {
		p = cfg.HTTPSPort
	}
	if p == 443 {
		return ""
	}
	return ":" + strconv.Itoa(p)
}
