// Config is everything the Caddyfile depends on.
type Config struct {
	AdminSocket string
	HTTPSPort   int
	// HTTPPort, if set, redirects http:// on that port to HTTPS on
	// PublicHTTPS (the port in addresses, which may be forwarded to
	// HTTPSPort).
	HTTPPort    int
	PublicHTTPS int
	// Phone, if set, serves one site on the private network addresses.
	Phone      *Phone
	StorageDir string
	LogFile    string
	CA         CA
	Sites      []Site
	// Adminer, when set, is served at https://adminer.localhost.
	Adminer *Adminer
	// MailUIPort, when set, proxies https://mail.localhost to Mailpit.
	MailUIPort int
}

// Adminer is the database manager: one PHP file served by PHP-FPM.
type Adminer struct {
	Dir       string // holds index.php, which loads Adminer
	FPMSocket string
}

// Reserved domains.
const (
	AdminerDomain = "adminer.localhost"
	MailDomain    = "mail.localhost"
)

// CA is the certificate authority Caddy signs site certificates with. Covo
// creates it (package ca): Caddy gets the root certificate without its key,
// and the intermediate with its key.
type CA struct {
	Name             string
	RootCert         string
	IntermediateCert string
	IntermediateKey  string
}

// Site is one virtual host.
type Site struct {
	Name      string
	Domain    string
	Aliases   []string
	Root      string
	FPMSocket string
	// AccessLog is the site's own request log; empty means none.
	AccessLog string
	// PHPValue is sent to PHP-FPM as PHP_VALUE: name=value lines (the
	// site's php.ini settings and error log).
	PHPValue string
}

var tmpl = template.Must(template.New("Caddyfile").Funcs(template.FuncMap{"q": quote}).Parse(`# Generated by Covo. Do not edit: changes are overwritten.
{
	admin {{q (print "unix/" .AdminSocket)}}
	persist_config off
	https_port {{.HTTPSPort}}
	default_bind 127.0.0.1 [::1]
	auto_https disable_redirects
	skip_install_trust
	storage file_system {{q .StorageDir}}
	pki {
		ca local {
			name {{q .CA.Name}}
			root {
				format pem_file
				cert {{q .CA.RootCert}}
			}
			intermediate {
				format pem_file
				cert {{q .CA.IntermediateCert}}
				key {{q .CA.IntermediateKey}}
			}
		}
	}
	log {
		output file {{q .LogFile}} {
			roll_size 10MiB
			roll_keep 3
		}
	}
}
{{range .Sites}}
# site: {{.Name}}
{{q (print "https://" .Domain ":" $.HTTPSPort)}}{{range .Aliases}}, {{q (print "https://" . ":" $.HTTPSPort)}}{{end}} {
	tls internal
	root * {{q .Root}}
	{{- if .AccessLog}}
	log {
		output file {{q .AccessLog}} {
			roll_size 5MiB
			roll_keep 2
		}
	}
	{{- end}}
	php_fastcgi {{q (print "unix/" .FPMSocket)}}
	{{- if .PHPValue}} {
		env PHP_VALUE {{q .PHPValue}}
	}
	{{- end}}
	file_server
}
{{end}}
{{- with .Adminer}}
# adminer
{{q (print "https://adminer.localhost:" $.HTTPSPort)}} {
	tls internal
	root * {{q .Dir}}
	rewrite * /index.php
	php_fastcgi {{q (print "unix/" .FPMSocket)}}
}
{{end}}
{{- if .HTTPPort}}
# http → https
{{q (print "http://:" .HTTPPort)}} {
	redir {{q (print "https://{host}" .RedirectPort "{uri}")}} 308
}
{{end}}
{{- with .Phone}}
# phone: {{.Site}}
{{q (print "https://" .Host ":" .Port)}} {
	bind{{range .Binds}} {{.}}{{end}}
	tls internal
	root * {{q .Root}}
	header >Location {{q .LocalURL}} {{q .PhoneURL}}
	php_fastcgi {{q (print "unix/" .FPMSocket)}} {
		env PHP_VALUE {{q .PHPValue}}
		env COVO_PHONE_URL {{q .PhoneURL}}
		env COVO_LOCAL_URL {{q .LocalURL}}
		{{- if .Laravel}}
		env APP_URL {{q .PhoneURL}}
		{{- end}}
	}
	file_server
}
{{q (print "http://:" .CAPort)}} {
	bind{{range .Binds}} {{.}}{{end}}
	root * {{q .CADir}}
	header /covo-ca.mobileconfig Content-Type application/x-apple-aspen-config
	header /covo-ca.crt Content-Type application/x-x509-ca-cert
	file_server
}
{{end}}
{{- if .MailUIPort}}
# mail
{{q (print "https://mail.localhost:" $.HTTPSPort)}} {
	tls internal
	reverse_proxy 127.0.0.1:{{.MailUIPort}}
}
{{end}}`))

// Phone is a site opened on a phone: served under Host on the Mac's private
// addresses (Binds) only, plus a plain-HTTP page that installs the CA.
type Phone struct {
	Site      string
	Host      string
	Port      int
	Binds     []string
	Root      string
	FPMSocket string
	// PHPValue includes Covo's auto_prepend_file for these requests.
	PHPValue string
	// LocalURL is replaced by PhoneURL in redirects (and, by the prepend
	// file, in pages).
	LocalURL, PhoneURL string
	// Laravel gets APP_URL from the environment.
	Laravel bool
	CAPort  int
	CADir   string
}

// Caddyfile renders cfg. Every path is validated with paths.CheckSafe so that
// it can be quoted verbatim (spaces are allowed).
func Caddyfile(cfg Config) (string, error) {
	check := []string{cfg.AdminSocket, cfg.StorageDir, cfg.LogFile, cfg.CA.RootCert, cfg.CA.IntermediateCert, cfg.CA.IntermediateKey}
	if cfg.Adminer != nil {
		check = append(check, cfg.Adminer.Dir, cfg.Adminer.FPMSocket)
	}
	if p := cfg.Phone; p != nil {
		check = append(check, p.Root, p.FPMSocket, p.CADir)
		if !hostRe.MatchString(p.Host) {
			return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad phone host %q", p.Host))
		}
		for _, b := range p.Binds {
			if ip := net.ParseIP(b); ip == nil || !ip.IsPrivate() {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("phone address %q is not a private IP", b))
			}
		}
		for _, line := range strings.Split(p.PHPValue, "\n") {
			if !phpValueRe.MatchString(line) {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad PHP value %q", line))
			}
		}
		for _, u := range []string{p.LocalURL, p.PhoneURL} {
			if strings.ContainsAny(u, "\"\\{} \n") {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad URL %q", u))
			}
		}
	}
	for _, s := range cfg.Sites {
		check = append(check, s.Root, s.FPMSocket)
		if s.AccessLog != "" {
			check = append(check, s.AccessLog)
		}
		for _, line := range strings.Split(s.PHPValue, "\n") {
			if s.PHPValue != "" && !phpValueRe.MatchString(line) {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad PHP value %q", line))
			}
		}
		for _, d := range append([]string{s.Domain}, s.Aliases...) {
			if !hostRe.MatchString(d) {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad domain %q", d))
			}
		}
	}
	for _, p := range check {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
	}
	if cfg.CA.Name == "" || strings.ContainsAny(cfg.CA.Name, "\"\\{}\n") {
		return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad CA name %q", cfg.CA.Name))
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return "", fmt.Errorf("render Caddyfile: %w", err)
	}
	return buf.String(), nil
}

// hostRe is what a domain may contain in the Caddyfile (the core checks
// the actual rules).
var hostRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)

// phpValueRe is one PHP_VALUE line that can sit verbatim in a quoted
// Caddyfile token.
var phpValueRe = regexp.MustCompile(`^[a-z_.]+=[^"\\{}$\x00-\x1f]+$`)

// quote wraps s in double quotes. CheckSafe guarantees s holds no quote,
// backslash or brace that would need escaping.
func quote(s string) string { return `"` + s + `"` }

// RedirectPort is ":port" for http → https redirects, or "" for 443.
func (cfg Config) RedirectPort() string {
	p := cfg.PublicHTTPS
	if p == 0 {
		p = cfg.HTTPSPort
	}
	if p == 443 {
		return ""
	}
	return ":" + strconv.Itoa(p)
}
