// Package caddy generates Covo's Caddyfile and talks to the running Caddy.
package caddy

import (
	"bytes"
	"fmt"
	"os"
	"strings"
	"text/template"

	"github.com/getcovo/covo/internal/errcode"
	"github.com/getcovo/covo/internal/paths"
)

// DefaultCAName is the name of Covo's local certificate authority, as shown
// in Keychain Access. untrust uses it to find the CA when its file is gone.
const DefaultCAName = "Covo Local CA"

// EnvCAName overrides the CA name, so that tests never touch the real CA.
const EnvCAName = "COVO_CA_NAME"

// CAName returns the CA name in effect.
func CAName() string {
	if n := os.Getenv(EnvCAName); n != "" {
		return n
	}
	return DefaultCAName
}

// Config is everything the Caddyfile depends on.
type Config struct {
	AdminSocket string
	HTTPSPort   int
	CAName      string // DefaultCAName if empty
	StorageDir  string
	LogFile     string
	Sites       []Site
}

// Site is one virtual host.
type Site struct {
	Name      string
	Domain    string
	Root      string
	FPMSocket string
}

var tmpl = template.Must(template.New("Caddyfile").Funcs(template.FuncMap{"q": quote}).Parse(`# Generated by Covo. Do not edit: changes are overwritten.
{
	admin {{q (print "unix/" .AdminSocket)}}
	persist_config off
	https_port {{.HTTPSPort}}
	default_bind 127.0.0.1 [::1]
	auto_https disable_redirects
	skip_install_trust
	storage file_system {{q .StorageDir}}
	pki {
		ca local {
			name {{q .CA}}
			root_cn {{q .CA}}
			intermediate_cn {{q (print .CA " Intermediate")}}
		}
	}
	log {
		output file {{q .LogFile}} {
			roll_size 10MiB
			roll_keep 3
		}
	}
}
{{range .Sites}}
# site: {{.Name}}
{{q (print "https://" .Domain ":" $.HTTPSPort)}} {
	tls internal
	root * {{q .Root}}
	php_fastcgi {{q (print "unix/" .FPMSocket)}}
	file_server
}
{{end}}`))

// Caddyfile renders cfg. Every path is validated with paths.CheckSafe so that
// it can be quoted verbatim (spaces are allowed).
func Caddyfile(cfg Config) (string, error) {
	check := []string{cfg.AdminSocket, cfg.StorageDir, cfg.LogFile}
	for _, s := range cfg.Sites {
		check = append(check, s.Root, s.FPMSocket)
	}
	for _, p := range check {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
	}
	var buf bytes.Buffer
	ca := cfg.CAName
	if ca == "" {
		ca = DefaultCAName
	}
	if strings.ContainsAny(ca, "\"\\{}\n") {
		return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad CA name %q", ca))
	}
	data := struct {
		Config
		CA string
	}{cfg, ca}
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render Caddyfile: %w", err)
	}
	return buf.String(), nil
}

// quote wraps s in double quotes. CheckSafe guarantees s holds no quote,
// backslash or brace that would need escaping.
func quote(s string) string { return `"` + s + `"` }
