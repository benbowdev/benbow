// Package caddy generates Covo's Caddyfile and talks to the running Caddy.
package caddy

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
	"text/template"

	"github.com/getcovo/covo/internal/errcode"
	"github.com/getcovo/covo/internal/paths"
)

// Config is everything the Caddyfile depends on.
type Config struct {
	AdminSocket string
	HTTPSPort   int
	StorageDir  string
	LogFile     string
	CA          CA
	Sites       []Site
}

// CA is the certificate authority Caddy signs site certificates with. Covo
// creates it (package ca): Caddy gets the root certificate without its key,
// and the intermediate with its key.
type CA struct {
	Name             string
	RootCert         string
	IntermediateCert string
	IntermediateKey  string
}

// Site is one virtual host.
type Site struct {
	Name      string
	Domain    string
	Aliases   []string
	Root      string
	FPMSocket string
}

var tmpl = template.Must(template.New("Caddyfile").Funcs(template.FuncMap{"q": quote}).Parse(`# Generated by Covo. Do not edit: changes are overwritten.
{
	admin {{q (print "unix/" .AdminSocket)}}
	persist_config off
	https_port {{.HTTPSPort}}
	default_bind 127.0.0.1 [::1]
	auto_https disable_redirects
	skip_install_trust
	storage file_system {{q .StorageDir}}
	pki {
		ca local {
			name {{q .CA.Name}}
			root {
				format pem_file
				cert {{q .CA.RootCert}}
			}
			intermediate {
				format pem_file
				cert {{q .CA.IntermediateCert}}
				key {{q .CA.IntermediateKey}}
			}
		}
	}
	log {
		output file {{q .LogFile}} {
			roll_size 10MiB
			roll_keep 3
		}
	}
}
{{range .Sites}}
# site: {{.Name}}
{{q (print "https://" .Domain ":" $.HTTPSPort)}}{{range .Aliases}}, {{q (print "https://" . ":" $.HTTPSPort)}}{{end}} {
	tls internal
	root * {{q .Root}}
	php_fastcgi {{q (print "unix/" .FPMSocket)}}
	file_server
}
{{end}}`))

// Caddyfile renders cfg. Every path is validated with paths.CheckSafe so that
// it can be quoted verbatim (spaces are allowed).
func Caddyfile(cfg Config) (string, error) {
	check := []string{cfg.AdminSocket, cfg.StorageDir, cfg.LogFile, cfg.CA.RootCert, cfg.CA.IntermediateCert, cfg.CA.IntermediateKey}
	for _, s := range cfg.Sites {
		check = append(check, s.Root, s.FPMSocket)
		for _, d := range append([]string{s.Domain}, s.Aliases...) {
			if !hostRe.MatchString(d) {
				return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad domain %q", d))
			}
		}
	}
	for _, p := range check {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
	}
	if cfg.CA.Name == "" || strings.ContainsAny(cfg.CA.Name, "\"\\{}\n") {
		return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad CA name %q", cfg.CA.Name))
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return "", fmt.Errorf("render Caddyfile: %w", err)
	}
	return buf.String(), nil
}

// hostRe is what a domain may contain in the Caddyfile (the core checks
// the actual rules).
var hostRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)

// quote wraps s in double quotes. CheckSafe guarantees s holds no quote,
// backslash or brace that would need escaping.
func quote(s string) string { return `"` + s + `"` }
