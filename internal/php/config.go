// Package php generates PHP-FPM and php.ini configuration.
package php

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/benbowdev/benbow/internal/errcode"
	"github.com/benbowdev/benbow/internal/paths"
)

// FPMConfig configures one PHP-FPM master (one per PHP minor version).
type FPMConfig struct {
	Minor    string
	Socket   string
	PIDFile  string
	ErrorLog string
}

// INIConfig configures php.ini for one PHP minor version.
type INIConfig struct {
	ErrorLog   string
	SessionDir string
	Timezone   string
	// CAFile is the CA bundle (Mozilla roots plus Benbow's root) PHP verifies
	// TLS with, so a site can call itself over HTTPS.
	CAFile string
	// MySQLSocket and MySQLPort, when MySQL is enabled, make "localhost"
	// (socket) and a bare "127.0.0.1" (no port) reach Benbow's MySQL, never
	// another server on 3306.
	MySQLSocket string
	MySQLPort   int
	// Extensions are shared extensions (absolute .so paths) of the PHP
	// build itself, loaded first; opcache.so as a Zend extension.
	Extensions []string
	// Xdebug is the absolute path of xdebug.so, or empty when off.
	Xdebug string
	// Settings are the user's values; the zero value means the defaults.
	Settings Settings
	// Sendmail, when set, is the Mailpit binary: mail() goes to Mailpit's
	// SMTP port instead of the Mac's own mail system.
	Sendmail     string
	SendmailPort int
}

var funcs = template.FuncMap{
	"q":    func(s string) string { return `"` + s + `"` },
	"zend": func(s string) bool { return filepath.Base(s) == "opcache.so" },
}

// listen.mode 0600: FPM runs as the user and only that user (Caddy) may
// connect. No user/group directives: FPM does not run as root.
var fpmTmpl = template.Must(template.New("php-fpm.conf").Funcs(funcs).Parse(`; Generated by Benbow. Do not edit: changes are overwritten.
[global]
pid = {{q .PIDFile}}
error_log = {{q .ErrorLog}}
daemonize = no

[benbow-{{.Minor}}]
listen = {{q .Socket}}
listen.mode = 0600
pm = ondemand
pm.max_children = 10
pm.process_idle_timeout = 30s
catch_workers_output = yes
{{- if .Decorates}}
decorate_workers_output = no
{{- end}}
`))

var iniTmpl = template.Must(template.New("php.ini").Funcs(funcs).Parse(`; Generated by Benbow. Do not edit: changes are overwritten.
memory_limit = {{.Settings.MemoryLimit}}
upload_max_filesize = {{.Settings.UploadMaxFilesize}}
post_max_size = {{.Settings.UploadMaxFilesize}}
max_execution_time = {{.Settings.MaxExecutionTime}}
max_input_vars = 5000

display_errors = {{if .Settings.DisplayErrors}}On{{else}}Off{{end}}
display_startup_errors = {{if .Settings.DisplayErrors}}On{{else}}Off{{end}}
error_reporting = E_ALL
log_errors = On
error_log = {{q .ErrorLog}}

date.timezone = {{q .Timezone}}
session.save_path = {{q .SessionDir}}
{{- if .Extensions}}
{{range .Extensions}}
{{if zend .}}zend_extension{{else}}extension{{end}} = {{q .}}
{{- end}}
{{- end}}

openssl.cafile = {{q .CAFile}}
curl.cainfo = {{q .CAFile}}
{{- if .MySQLPort}}

mysqli.default_socket = {{q .MySQLSocket}}
mysqli.default_port = {{.MySQLPort}}
pdo_mysql.default_socket = {{q .MySQLSocket}}
{{- end}}
{{- if .Sendmail}}

; Mail is caught by Mailpit (benbow mail).
sendmail_path = "'{{.Sendmail}}' sendmail -S 127.0.0.1:{{.SendmailPort}}"
{{- end}}
{{- if .Xdebug}}

; Xdebug: step debugging only, started by a trigger (browser extension,
; XDEBUG_TRIGGER cookie or parameter). The IDE listens on 127.0.0.1:9003.
zend_extension = {{q .Xdebug}}
xdebug.mode = debug
xdebug.start_with_request = trigger
xdebug.client_host = 127.0.0.1
xdebug.client_port = 9003
{{- end}}

opcache.enable = 1
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
`))

// FPMConf renders php-fpm.conf.
func FPMConf(c FPMConfig) (string, error) {
	if err := checkSafe(c.Socket, c.PIDFile, c.ErrorLog); err != nil {
		return "", err
	}
	return render(fpmTmpl, struct {
		FPMConfig
		Decorates bool
	}{c, atLeast(c.Minor, 7, 3)})
}

// atLeast reports whether minor ("7.4") is at least major.sub. FPM
// refuses directives older versions do not know.
func atLeast(minor string, major, sub int) bool {
	var a, b int
	if _, err := fmt.Sscanf(minor, "%d.%d", &a, &b); err != nil {
		return true
	}
	return a > major || (a == major && b >= sub)
}

// INI renders php.ini.
func INI(c INIConfig) (string, error) {
	if c.Settings == (Settings{}) {
		c.Settings = DefaultSettings()
	}
	if err := c.Settings.Validate(); err != nil {
		return "", err
	}
	if err := checkSafe(c.ErrorLog, c.SessionDir, c.CAFile); err != nil {
		return "", err
	}
	if c.MySQLPort != 0 {
		if err := checkSafe(c.MySQLSocket); err != nil {
			return "", err
		}
	}
	if err := checkSafe(c.Extensions...); err != nil {
		return "", err
	}
	if c.Xdebug != "" {
		if err := checkSafe(c.Xdebug); err != nil {
			return "", err
		}
	}
	if c.Sendmail != "" {
		// Single-quoted for the shell PHP runs it with.
		if err := checkSafe(c.Sendmail); err != nil {
			return "", err
		}
		if strings.Contains(c.Sendmail, "'") || c.SendmailPort <= 0 {
			return "", errcode.Newf(errcode.InvalidInput, "bad sendmail %q port %d", c.Sendmail, c.SendmailPort)
		}
	}
	return render(iniTmpl, c)
}

func checkSafe(ps ...string) error {
	for _, p := range ps {
		if err := paths.CheckSafe(p); err != nil {
			return err
		}
	}
	return nil
}

func render(t *template.Template, data any) (string, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render %s: %w", t.Name(), err)
	}
	return buf.String(), nil
}
