// MyCnf renders the server's option file.
func MyCnf(c Config) (string, error) {
	for _, p := range []string{c.BaseDir, c.DataDir, c.Socket, c.PIDFile, c.ErrorLog} {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
		// Option files treat these specially even inside quotes.
		if strings.ContainsAny(p, "#'") {
			return "", errcode.Newf(errcode.InvalidInput, "path %q contains unsupported character", p)
		}
	}
	if c.Port < 1024 || c.Port > 65535 {
		return "", errcode.Newf(errcode.InvalidInput, "bad MySQL port %d", c.Port)
	}
	var b bytes.Buffer
	if err := cnfTmpl.Execute(&b, c); err != nil {
		return "", fmt.Errorf("render my.cnf: %w", err)
	}
	return b.String(), nil
}

const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"

// NewPassword returns 24 random characters (about 140 bits) from an alphabet
// that needs no quoting anywhere: SQL, option files, `security -i`.
func NewPassword() string {
	b := make([]byte, 24)
	_, _ = rand.Read(b)
	for i := range b {
		b[i] = alphabet[int(b[i])%len(alphabet)]
	}
	return string(b)
}

func checkPassword(pw string) error {
	if len(pw) < 16 {
		return errcode.Errorf(errcode.InvalidInput, "MySQL password too short")
	}
	for _, r := range pw {
		if !strings.ContainsRune(alphabet, r) {
			return errcode.Errorf(errcode.InvalidInput, "MySQL password contains an unsupported character")
		}
	}
	return nil
}

// withFD3 runs cmd with body readable on /dev/fd/3 through a pipe.
func withFD3(cmd *exec.Cmd, body string) error {
	r, w, err := os.Pipe()
	if err != nil {
		return fmt.Errorf("pipe: %w", err)
	}
	cmd.ExtraFiles = []*os.File{r}
	if err := cmd.Start(); err != nil {
		_ = r.Close()
		_ = w.Close()
		return fmt.Errorf("start %s: %w", cmd.Path, err)
	}
	_ = r.Close()
	_, werr := io.WriteString(w, body)
	_ = w.Close()
	err = cmd.Wait()
	if err == nil && werr != nil {
		err = fmt.Errorf("write to %s: %w", cmd.Path, werr)
	}
	return err
}

// Initialize creates a new data directory in dataDir (which overrides the
// option file's) with root@localhost protected by password from the first
// moment: the ALTER USER runs as the --init-file of the bootstrap, read from
// a pipe.
func Initialize(ctx context.Context, mysqld, cnf, dataDir, password string) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 3*time.Minute)
	defer cancel()
	var out bytes.Buffer
	cmd := exec.CommandContext(ctx, mysqld, "--defaults-file="+cnf, "--datadir="+dataDir, "--initialize-insecure", "--init-file=/dev/fd/3")
	cmd.Stdout, cmd.Stderr = &out, &out
	sql := "ALTER USER '" + User + "'@'localhost' IDENTIFIED BY '" + password + "';\n"
	if err := withFD3(cmd, sql); err != nil {
		return errcode.New(errcode.Service, fmt.Errorf("initialize MySQL data directory: %w: %s", err, strings.TrimSpace(out.String())))
	}
	return nil
}

// Query runs sql as root with the mysql client over TCP on 127.0.0.1:port, passing
// the password through /dev/fd/3, and returns the tab-separated output.
func Query(ctx context.Context, client string, port int, password, sql string) (string, error) {
	if err := checkPassword(password); err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	var out, errOut bytes.Buffer
	// The SQL goes through stdin: it may hold passwords, which must never
	// appear in a process list.
	cmd := exec.CommandContext(ctx, client, "--defaults-extra-file=/dev/fd/3",
		"--protocol=TCP", "-h", "127.0.0.1", "-P", strconv.Itoa(port), "-u", User,
		"--batch", "--skip-column-names")
	cmd.Stdin = strings.NewReader(sql)
	cmd.Stdout, cmd.Stderr = &out, &errOut
	if err := withFD3(cmd, "[client]\npassword="+password+"\n"); err != nil {
		return "", errcode.New(errcode.Service, fmt.Errorf("mysql: %w: %s", err, strings.TrimSpace(errOut.String())))
	}
	return out.String(), nil
}

// Keychain keeps MySQL passwords as generic password items: one per
// account (root, and each site's own user) under one service.
type Keychain struct {
	Path    string // keychain file
	Service string // item service name, e.g. dev.benbow.mysql
	// Account is the MySQL user; empty means root.
	Account string
	// Run executes /usr/bin/security with stdin; overridable in tests.
	Run keychain.Runner
}

// ErrNoPassword means the keychain holds no password for Service.
var ErrNoPassword = keychain.ErrNotFound

func (k Keychain) account() string {
	if k.Account == "" {
		return User
	}
	return k.Account
}

func (k Keychain) item() keychain.Item {
	label := "Benbow MySQL (" + k.Service + ")"
	if k.account() != User {
		label = "Benbow MySQL " + k.account() + " (" + k.Service + ")"
	}
	return keychain.Item{Path: k.Path, Service: k.Service, Account: k.account(), Label: label, Run: k.Run}
}

// For returns the same keychain entry for another MySQL user.
func (k Keychain) For(account string) Keychain {
	k.Account = account
	return k
}

// Set stores password, replacing any previous one. Only passwords Benbow
// could have generated are accepted: they go unquoted into option files
// and SQL.
func (k Keychain) Set(ctx context.Context, password string) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	if !accountRe.MatchString(k.account()) {
		return errcode.Errorf(errcode.InvalidInput, "unsupported keychain account")
	}
	return k.item().Set(ctx, password)
}

// Get returns the stored password, or ErrNoPassword.
func (k Keychain) Get(ctx context.Context) (string, error) { return k.item().Get(ctx) }

// Exists reports whether a password is stored.
func (k Keychain) Exists(ctx context.Context) (bool, error) { return k.item().Exists(ctx) }

// Delete removes the stored password. It is a no-op if there is none.
func (k Keychain) Delete(ctx context.Context) (bool, error) { return k.item().Delete(ctx) }

// DeleteAll removes every password stored under Service, whatever the
// account, and returns how many were removed.
func (k Keychain) DeleteAll(ctx context.Context) (int, error) { return k.item().DeleteAll(ctx) }

// AnyExists reports whether any password is stored under Service.
func (k Keychain) AnyExists(ctx context.Context) (bool, error) { return k.item().AnyExists(ctx) }

// accountRe is a MySQL user Benbow creates: also safe in `security -i`.
var accountRe = regexp.MustCompile(`^[a-z0-9_]{1,32}$`)

// ValidName reports whether name may be used as a database or user name
// by Benbow: lowercase letters, digits and underscores, so that it never
// needs quoting beyond backticks.
func ValidName(name string, maxLen int) bool {
	return len(name) <= maxLen && nameRe.MatchString(name)
}

var nameRe = regexp.MustCompile(`^[a-z0-9_]+$`)

// QueryAs runs sql as user on db and returns the tab-separated output with
// a first line of column names (batch mode: tabs and newlines in values
// are escaped). The password goes through /dev/fd/3. legacy is a MySQL 5.7
// client, which has no --skip-system-command: the caller keeps client
// commands out of sql itself.
func QueryAs(ctx context.Context, client string, port int, user, password, db, sql string, timeout time.Duration, legacy bool) (string, error) {
	if err := checkPassword(password); err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	var out, errOut bytes.Buffer
	args := []string{"--defaults-extra-file=/dev/fd/3",
		"--protocol=TCP", "-h", "127.0.0.1", "-P", strconv.Itoa(port), "-u", user, "-D", db, "--batch"}
	if !legacy {
		args = append(args, "--skip-system-command")
	}
	cmd := exec.CommandContext(ctx, client, args...)
	cmd.Stdin = strings.NewReader(sql)
	cmd.Stdout, cmd.Stderr = &out, &errOut
	if err := withFD3(cmd, "[client]\npassword="+password+"\n"); err != nil {
		msg := strings.TrimSpace(errOut.String())
		if ctx.Err() != nil {
			msg = "stopped after " + timeout.String()
		}
		return "", errcode.New(errcode.InvalidInput, fmt.Errorf("mysql: %s", msg))
	}
	return out.String(), nil
}
