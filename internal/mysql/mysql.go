// Package mysql configures and initializes Covo's MySQL server, and keeps its
// root password in the login keychain.
//
// The password never appears in a command line, an environment variable or
// a file: it reaches mysqld and the mysql client through an inherited pipe
// (/dev/fd/3), and the keychain through the standard input of
// `security -i`.
package mysql

import (
	"bytes"
	"context"
	"crypto/rand"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"strconv"
	"strings"
	"text/template"
	"time"

	"github.com/getcovo/covo/internal/errcode"
	"github.com/getcovo/covo/internal/paths"
)

// DefaultPort is the first port tried: 3306 is usually MAMP's.
const DefaultPort = 3307

// User is the account Covo creates and keeps the password of.
const User = "root"

// Config is what my.cnf is rendered from.
type Config struct {
	BaseDir  string // the installed component: bin/, lib/, share/
	DataDir  string
	Socket   string
	PIDFile  string
	ErrorLog string
	Port     int
}

var cnfTmpl = template.Must(template.New("my.cnf").Parse(`# Generated by Covo. Do not edit: changes are overwritten.
[mysqld]
basedir="{{.BaseDir}}"
datadir="{{.DataDir}}"
lc-messages-dir="{{.BaseDir}}/share"
character-sets-dir="{{.BaseDir}}/share/charsets"
socket="{{.Socket}}"
pid-file="{{.PIDFile}}"
log-error="{{.ErrorLog}}"
# Loopback only; no X Protocol port.
bind-address=127.0.0.1
port={{.Port}}
mysqlx=OFF
# A development server: no binary log, no performance schema (saves ~400 MB).
disable-log-bin
performance_schema=OFF
max_allowed_packet=64M
`))

// MyCnf renders the server's option file.
func MyCnf(c Config) (string, error) {
	for _, p := range []string{c.BaseDir, c.DataDir, c.Socket, c.PIDFile, c.ErrorLog} {
		if err := paths.CheckSafe(p); err != nil {
			return "", err
		}
		// Option files treat these specially even inside quotes.
		if strings.ContainsAny(p, "#'") {
			return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("path %q contains unsupported character", p))
		}
	}
	if c.Port < 1024 || c.Port > 65535 {
		return "", errcode.Errorf(errcode.InvalidInput, fmt.Sprintf("bad MySQL port %d", c.Port))
	}
	var b bytes.Buffer
	if err := cnfTmpl.Execute(&b, c); err != nil {
		return "", fmt.Errorf("render my.cnf: %w", err)
	}
	return b.String(), nil
}

const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"

// NewPassword returns 24 random characters (about 140 bits) from an alphabet
// that needs no quoting anywhere: SQL, option files, `security -i`.
func NewPassword() string {
	b := make([]byte, 24)
	_, _ = rand.Read(b)
	for i := range b {
		b[i] = alphabet[int(b[i])%len(alphabet)]
	}
	return string(b)
}

func checkPassword(pw string) error {
	if len(pw) < 16 {
		return errcode.Errorf(errcode.InvalidInput, "MySQL password too short")
	}
	for _, r := range pw {
		if !strings.ContainsRune(alphabet, r) {
			return errcode.Errorf(errcode.InvalidInput, "MySQL password contains an unsupported character")
		}
	}
	return nil
}

// withFD3 runs cmd with body readable on /dev/fd/3 through a pipe.
func withFD3(cmd *exec.Cmd, body string) error {
	r, w, err := os.Pipe()
	if err != nil {
		return fmt.Errorf("pipe: %w", err)
	}
	cmd.ExtraFiles = []*os.File{r}
	if err := cmd.Start(); err != nil {
		_ = r.Close()
		_ = w.Close()
		return fmt.Errorf("start %s: %w", cmd.Path, err)
	}
	_ = r.Close()
	_, werr := io.WriteString(w, body)
	_ = w.Close()
	err = cmd.Wait()
	if err == nil && werr != nil {
		err = fmt.Errorf("write to %s: %w", cmd.Path, werr)
	}
	return err
}

// Initialize creates a new data directory in dataDir (which overrides the
// option file's) with root@localhost protected by password from the first
// moment: the ALTER USER runs as the --init-file of the bootstrap, read from
// a pipe.
func Initialize(ctx context.Context, mysqld, cnf, dataDir, password string) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 3*time.Minute)
	defer cancel()
	var out bytes.Buffer
	cmd := exec.CommandContext(ctx, mysqld, "--defaults-file="+cnf, "--datadir="+dataDir, "--initialize-insecure", "--init-file=/dev/fd/3")
	cmd.Stdout, cmd.Stderr = &out, &out
	sql := "ALTER USER '" + User + "'@'localhost' IDENTIFIED BY '" + password + "';\n"
	if err := withFD3(cmd, sql); err != nil {
		return errcode.New(errcode.Service, fmt.Errorf("initialize MySQL data directory: %w: %s", err, strings.TrimSpace(out.String())))
	}
	return nil
}

// Query runs sql with the mysql client over TCP on 127.0.0.1:port, passing
// the password through /dev/fd/3, and returns the tab-separated output.
func Query(ctx context.Context, client string, port int, password, sql string) (string, error) {
	if err := checkPassword(password); err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	var out, errOut bytes.Buffer
	cmd := exec.CommandContext(ctx, client, "--defaults-extra-file=/dev/fd/3",
		"--protocol=TCP", "-h", "127.0.0.1", "-P", strconv.Itoa(port), "-u", User,
		"--batch", "--skip-column-names", "-e", sql)
	cmd.Stdout, cmd.Stderr = &out, &errOut
	if err := withFD3(cmd, "[client]\npassword="+password+"\n"); err != nil {
		return "", errcode.New(errcode.Service, fmt.Errorf("mysql: %w: %s", err, strings.TrimSpace(errOut.String())))
	}
	return out.String(), nil
}

// Keychain keeps the root password as a generic password item.
type Keychain struct {
	Path    string // keychain file
	Service string // item service name, e.g. dev.getcovo.mysql
	// Run executes /usr/bin/security with stdin; overridable in tests.
	Run func(ctx context.Context, stdin string, args ...string) (string, error)
}

// ErrNoPassword means the keychain holds no password for Service.
var ErrNoPassword = errors.New("no MySQL password in the keychain")

func (k Keychain) run(ctx context.Context, stdin string, args ...string) (string, error) {
	if k.Run != nil {
		return k.Run(ctx, stdin, args...)
	}
	ctx, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()
	var out bytes.Buffer
	cmd := exec.CommandContext(ctx, "/usr/bin/security", args...)
	cmd.Stdin = strings.NewReader(stdin)
	cmd.Stdout, cmd.Stderr = &out, &out
	err := cmd.Run()
	return out.String(), err
}

// Set stores password, replacing any previous one. The password goes through
// stdin of `security -i`, never through arguments.
func (k Keychain) Set(ctx context.Context, password string) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	if strings.ContainsAny(k.Service+k.Path, "\"\\\n") {
		return errcode.Errorf(errcode.InvalidInput, "unsupported keychain service or path")
	}
	line := fmt.Sprintf("add-generic-password -U -a %s -s \"%s\" -l \"%s\" -j \"Created by Covo. Removed by covo uninstall.\" -w %s \"%s\"\n",
		User, k.Service, "Covo MySQL ("+k.Service+")", password, k.Path)
	if _, err := k.run(ctx, line, "-i"); err != nil {
		return errcode.New(errcode.Service, fmt.Errorf("store MySQL password in the keychain: %w", err))
	}
	// `security -i` exits 0 even when a command fails: read it back.
	got, err := k.Get(ctx)
	if err != nil {
		return err
	}
	if got != password {
		return errcode.Errorf(errcode.Service, "the keychain did not store the MySQL password")
	}
	return nil
}

// Get returns the stored password, or ErrNoPassword.
func (k Keychain) Get(ctx context.Context) (string, error) {
	out, err := k.run(ctx, "", "find-generic-password", "-a", User, "-s", k.Service, "-w", k.Path)
	if err != nil {
		if strings.Contains(out, "could not be found") {
			return "", ErrNoPassword
		}
		return "", errcode.New(errcode.Service, fmt.Errorf("read MySQL password from the keychain: %w: %s", err, strings.TrimSpace(out)))
	}
	return strings.TrimSpace(out), nil
}

// Exists reports whether a password is stored.
func (k Keychain) Exists(ctx context.Context) (bool, error) {
	_, err := k.Get(ctx)
	if errors.Is(err, ErrNoPassword) {
		return false, nil
	}
	return err == nil, err
}

// Delete removes the stored password. It is a no-op if there is none.
func (k Keychain) Delete(ctx context.Context) (bool, error) {
	out, err := k.run(ctx, "", "delete-generic-password", "-a", User, "-s", k.Service, k.Path)
	if err != nil {
		if strings.Contains(out, "could not be found") {
			return false, nil
		}
		return false, errcode.New(errcode.Service, fmt.Errorf("remove MySQL password from the keychain: %w: %s", err, strings.TrimSpace(out)))
	}
	return true, nil
}
