// Package mysql configures and initializes Benbow's MySQL server, and keeps its
// root password in the login keychain.
//
// The password never appears in a command line, an environment variable or
// a file: it reaches mysqld and the mysql client through an inherited pipe
// (/dev/fd/3), and the keychain through the standard input of
// `security -i`.
