// Package resolver manages Benbow's file in /etc/resolver, which tells macOS to
// ask Benbow's DNS server (127.0.0.1, high port) for one zone such as "test".
//
// /etc is owned by root: installing or removing the file takes one
// administrator authorization, through the standard macOS dialog. The file
// records the Benbow home that owns it, so that a Benbow installation never
// removes another one's file, and whether Benbow created /etc/resolver, so
// that removing the file restores the directory as it was.
package resolver

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/benbowdev/benbow/internal/errcode"
	"github.com/benbowdev/benbow/internal/paths"
)

// SystemDir is macOS's per-domain resolver directory.
const SystemDir = "/etc/resolver"

const (
	headerLine  = "# Generated by Benbow. Removed by `benbow domains disable` and `benbow uninstall`."
	homeKey     = "# benbow-home: "
	createdKey  = "# benbow-created-dir: "
	nameserver  = "nameserver 127.0.0.1"
	portKeyword = "port "
)

// File is the content of Benbow's resolver file for one zone.
type File struct {
	Home       string // Benbow home that owns the file
	Port       int
	CreatedDir bool // Benbow created the resolver directory
}

// Render returns the file content.
func (f File) Render() string {
	created := "no"
	if f.CreatedDir {
		created = "yes"
	}
	return headerLine + "\n" + homeKey + f.Home + "\n" + createdKey + created + "\n" +
		nameserver + "\n" + portKeyword + strconv.Itoa(f.Port) + "\n"
}

// Parse reads a resolver file. ok is false when it was not written by Benbow.
func Parse(content string) (f File, ok bool) {
	sc := bufio.NewScanner(strings.NewReader(content))
	first := true
	for sc.Scan() {
		line := sc.Text()
		if first {
			if line != headerLine {
				return File{}, false
			}
			first = false
			continue
		}
		switch {
		case strings.HasPrefix(line, homeKey):
			f.Home = strings.TrimPrefix(line, homeKey)
		case strings.HasPrefix(line, createdKey):
			f.CreatedDir = strings.TrimPrefix(line, createdKey) == "yes"
		case strings.HasPrefix(line, portKeyword):
			f.Port, _ = strconv.Atoi(strings.TrimPrefix(line, portKeyword))
		}
	}
	return f, !first && f.Home != "" && f.Port > 0
}

// Runner runs a shell command, with administrator privileges when the
// target needs them. prompt explains why, in the macOS dialog.
type Runner func(ctx context.Context, prompt, command string) error

// Admin runs command as root through the standard macOS authorization
// dialog (AppleScript "with administrator privileges"). It never runs sudo
// and never sees the password.
func Admin(ctx context.Context, prompt, command string) error {
	if strings.ContainsAny(command+prompt, "\"\\") {
		return errcode.Errorf(errcode.Internal, "refusing to pass quotes or backslashes to AppleScript")
	}
	script := fmt.Sprintf(`do shell script "%s" with prompt "%s" with administrator privileges`, command, prompt)
	out, err := exec.CommandContext(ctx, "/usr/bin/osascript", "-e", script).CombinedOutput()
	if err != nil {
		if strings.Contains(string(out), "-128") {
			return errcode.Errorf(errcode.ConfirmationRequired, "administrator authorization was cancelled")
		}
		return errcode.New(errcode.Service, fmt.Errorf("osascript: %w: %s", err, strings.TrimSpace(string(out))))
	}
	return nil
}

// Direct runs command as the current user. It is used when the resolver
// directory is not a system one (tests).
func Direct(ctx context.Context, _, command string) error {
	out, err := exec.CommandContext(ctx, "/bin/sh", "-c", command).CombinedOutput()
	if err != nil {
		return errcode.New(errcode.Service, fmt.Errorf("%s: %w: %s", command, err, strings.TrimSpace(string(out))))
	}
	return nil
}

// Manager installs and removes Benbow's resolver files in Dir.
type Manager struct {
	Dir  string
	Home string // the Benbow home this installation belongs to
	Run  Runner
	// TmpDir holds the staged file the privileged command copies.
	TmpDir string
}

// Path is the resolver file of zone.
func (m Manager) Path(zone string) string { return filepath.Join(m.Dir, zone) }

// State describes the resolver file of a zone.
type State struct {
	Path      string `json:"path"`
	Installed bool   `json:"installed"`
	Port      int    `json:"port,omitempty"`
	// Foreign is true when a file exists that Benbow did not write for this
	// home (another tool, or another Benbow home).
	Foreign bool `json:"foreign,omitempty"`
}

// State reads the resolver file of zone.
func (m Manager) State(zone string) (State, File, error) {
	st := State{Path: m.Path(zone)}
	b, err := os.ReadFile(st.Path)
	if errors.Is(err, os.ErrNotExist) {
		return st, File{}, nil
	}
	if err != nil {
		return st, File{}, fmt.Errorf("read %s: %w", st.Path, err)
	}
	f, ok := Parse(string(b))
	if !ok || f.Home != m.Home {
		st.Foreign = true
		return st, File{}, nil
	}
	st.Installed, st.Port = true, f.Port
	return st, f, nil
}

func checkZone(zone string) error {
	for _, r := range zone {
		if (r < 'a' || r > 'z') && (r < '0' || r > '9') && r != '-' {
			return errcode.Newf(errcode.InvalidInput, "bad zone %q", zone)
		}
	}
	if zone == "" {
		return errcode.Errorf(errcode.InvalidInput, "empty zone")
	}
	return nil
}

// shellQuote quotes p for /bin/sh. p must already be a safe path.
func shellQuote(p string) (string, error) {
	if err := paths.CheckSafe(p); err != nil {
		return "", err
	}
	if strings.Contains(p, "'") {
		return "", errcode.Newf(errcode.InvalidInput, "path %q contains a quote", p)
	}
	return "'" + p + "'", nil
}

// Install writes the resolver file for zone pointing at port. It changes
// nothing (and asks for nothing) when the file is already right, and
// refuses to overwrite a file it did not write.
func (m Manager) Install(ctx context.Context, zone string, port int) (changed bool, err error) {
	if err := checkZone(zone); err != nil {
		return false, err
	}
	st, cur, err := m.State(zone)
	if err != nil {
		return false, err
	}
	if st.Foreign {
		return false, errcode.Newf(errcode.Conflict,
			"%s exists and was not created by this Benbow installation; remove it yourself if it is not needed", st.Path)

	}
	_, dirErr := os.Stat(m.Dir)
	want := File{Home: m.Home, Port: port, CreatedDir: errors.Is(dirErr, os.ErrNotExist)}
	if st.Installed {
		if cur.Port == port {
			return false, nil
		}
		want.CreatedDir = cur.CreatedDir
	}
	if err := os.MkdirAll(m.TmpDir, 0o700); err != nil {
		return false, fmt.Errorf("create %s: %w", m.TmpDir, err)
	}
	staged := filepath.Join(m.TmpDir, "resolver-"+zone)
	if err := os.WriteFile(staged, []byte(want.Render()), 0o644); err != nil {
		return false, fmt.Errorf("stage resolver file: %w", err)
	}
	defer os.Remove(staged)

	src, err := shellQuote(staged)
	if err != nil {
		return false, err
	}
	dir, err := shellQuote(m.Dir)
	if err != nil {
		return false, err
	}
	dst, err := shellQuote(m.Path(zone))
	if err != nil {
		return false, err
	}
	tmp, err := shellQuote(m.Path("." + zone + ".benbow-new"))
	if err != nil {
		return false, err
	}
	// Copy then rename: the file appears complete or not at all. A file
	// created by root is owned by root:wheel.
	cmd := fmt.Sprintf("/bin/mkdir -p %s && /bin/cp %s %s && /bin/chmod 0644 %s && /bin/mv -f %s %s",
		dir, src, tmp, tmp, tmp, dst)
	prompt := fmt.Sprintf("Benbow wants to send .%s lookups to its local DNS server (127.0.0.1 port %d).", zone, port)
	if err := m.Run(ctx, prompt, cmd); err != nil {
		return false, err
	}
	if st, _, err := m.State(zone); err != nil || !st.Installed {
		return false, errcode.Errorf(errcode.Service, "the resolver file was not installed")
	}
	return true, nil
}

// Remove deletes Benbow's resolver file for zone, and the resolver directory
// if Benbow created it and it is now empty. It is a no-op without a file, and
// never touches a file Benbow did not write for this home.
func (m Manager) Remove(ctx context.Context, zone string) (changed bool, err error) {
	if err := checkZone(zone); err != nil {
		return false, err
	}
	st, cur, err := m.State(zone)
	if err != nil || !st.Installed {
		return false, err
	}
	dst, err := shellQuote(m.Path(zone))
	if err != nil {
		return false, err
	}
	cmd := "/bin/rm -f " + dst
	if cur.CreatedDir {
		dir, err := shellQuote(m.Dir)
		if err != nil {
			return false, err
		}
		// rmdir only removes an empty directory.
		cmd += " && { /bin/rmdir " + dir + " 2>/dev/null || true; }"
	}
	prompt := fmt.Sprintf("Benbow wants to stop handling .%s domains and remove its resolver file.", zone)
	if err := m.Run(ctx, prompt, cmd); err != nil {
		return false, err
	}
	if _, err := os.Stat(st.Path); err == nil {
		return false, errcode.Errorf(errcode.Service, "the resolver file was not removed")
	}
	return true, nil
}
